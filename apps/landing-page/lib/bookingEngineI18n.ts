// ── Translation Function with Fallback ──
export const translate = (
    langCode: string,
    key: TranslationKey,
    params?: Record<string, string | number>
): string => {
    // Normalise language code (e.g. en-GB -> en, zh-TW -> zh-CN fallback if needed)
    const baseCode = langCode.split("-")[0];
    const dict = TRANSLATIONS[langCode] || TRANSLATIONS[baseCode] || TRANSLATIONS["id"] || TRANSLATIONS["en"];
    let text = dict[key] || TRANSLATIONS["id"]?.[key] || TRANSLATIONS["en"]?.[key] || key;

    if (params) {
        Object.entries(params).forEach(([pKey, pVal]) => {
            text = text.replace(new RegExp(`\\{${pKey}\\}`, "g"), String(pVal));
        });
    }

    return text;
};

// ── Currency Formatter ──
export const formatPriceWithCurrency = (
    amountInIdr: number,
    currencyCode: string = "IDR"
): string => {
    const cur = ALL_CURRENCIES.find((c) => c.code.toUpperCase() === currencyCode.toUpperCase()) || ALL_CURRENCIES[0];
    const converted = amountInIdr * cur.rateFromIdr;

    if (cur.code === "IDR") {
        return new Intl.NumberFormat("id-ID", {
            style: "currency",
            currency: "IDR",
            maximumFractionDigits: 0,
        }).format(amountInIdr);
    }

    try {
        return new Intl.NumberFormat("en-US", {
            style: "currency",
            currency: cur.code,
            minimumFractionDigits: cur.decimals,
            maximumFractionDigits: cur.decimals,
        }).format(converted);
    } catch {
        // Fallback for custom or unsupported currency formatting in Intl
        const formattedNum = converted.toLocaleString("en-US", {
            minimumFractionDigits: cur.decimals,
            maximumFractionDigits: cur.decimals,
        });
        return `${cur.symbol} ${formattedNum}`;
    }
};
